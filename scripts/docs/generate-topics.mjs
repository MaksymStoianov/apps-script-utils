const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

const SRC = join(ROOT, "src");

const CONTENT = join(ROOT, "docs/content");

const REPO = "https://github.com/MaksymStoianov/apps-script-utils/blob/main";

const MARKER = "<!-- Generated by scripts/docs/generate-topics.mjs. Edits are overwritten.";

const CHECK = process.argv.includes("--check");

/**
 * Errors the runtime itself raises, which no `throw new` statement shows.
 */
const BUILT_IN_ERRORS = new Set(["Error", "TypeError", "SyntaxError", "RangeError"]);

const stale = [];

let written = 0;

let kept = 0;

/**
 * Writes a file, or records it as out of date under `--check`.
 */
function emit(path, content) {
  let existing = null;

  try {
    existing = readFileSync(path, "utf8");
  } catch {
    existing = null;
  }

  if (existing === content) {
    return;
  }

  if (CHECK) {
    stale.push(relative(ROOT, path));

    return;
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  written += 1;
}

async function pretty(content, filepath) {
  const options = await prettier.resolveConfig(filepath);

  return prettier.format(content, { ...options, filepath });
}

function readIfExists(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

// --- facts from the code --------------------------------------------------

function referenceTopicOf(relPath) {
  if (relPath.startsWith("exception/")) {
    return "reference-exception.md";
  }

  if (relPath.startsWith("appsscript/")) {
    return "reference-appsscript.md";
  }

  if (relPath.startsWith("net/path/")) {
    return "reference-path.md";
  }

  if (relPath === "lang/Class.ts" || relPath === "lang/Iterator.ts") {
    return "reference-abstracts.md";
  }

  return "reference-base.md";
}

function moduleOf(relPath) {
  const dir = dirname(relPath);

  return dir === "." ? "src" : dir;
}

function listFiles(dir, filter) {
  const out = [];

  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);

    if (statSync(full).isDirectory()) {
      out.push(...listFiles(full, filter));

      continue;
    }

    if (filter(entry)) {
      out.push(full);
    }
  }

  return out;
}

function isExported(node) {
  return (ts.getCombinedModifierFlags(node) & ts.ModifierFlags.Export) !== 0;
}

function commentToText(comment) {
  if (typeof comment === "string") {
    return comment;
  }

  if (!comment) {
    return "";
  }

  return comment
    .map((part) =>
      ts.isJSDocLink(part) || ts.isJSDocLinkCode(part) || ts.isJSDocLinkPlain(part)
        ? `{@link ${part.name?.getText() ?? ""}${part.text ?? ""}}`
        : part.text
    )
    .join("");
}

/**
 * The `@throws` entries, read from the raw comment: TypeScript drops them.
 */
function rawThrows(doc) {
  const text = doc
    .getText()
    .split("\n")
    .map((line) => line.replace(/^\s*\/?\*+\/?/, "").trim())
    .join("\n");

  const found = [];

  for (const match of text.matchAll(/@throws\s+([\s\S]*?)(?=\n\s*@\w|$)/g)) {
    const entry = match[1].replace(/\s+/g, " ").trim();

    if (entry) {
      found.push(entry);
    }
  }

  return found;
}

function throwsParts(text) {
  const linked = text.match(/^\{\s*@link\s+([\w.]+)\s*\}\s*(.*)$/s);

  if (linked) {
    return { type: linked[1], when: linked[2].trim() };
  }

  const braced = text.match(/^\{\s*([\w.]+)\s*\}\s*(.*)$/s);

  if (braced) {
    return { type: braced[1], when: braced[2].trim() };
  }

  const words = text.trim().split(/\s+/);

  return { type: words[0] ?? "", when: words.slice(1).join(" ") };
}

/**
 * The exception classes a function body actually constructs and throws.
 */
function thrownClasses(nodes) {
  const found = [];

  for (const node of nodes) {
    if (!node.body) {
      continue;
    }

    const visit = (child) => {
      if (
        ts.isThrowStatement(child) &&
        child.expression &&
        ts.isNewExpression(child.expression) &&
        child.expression.expression
      ) {
        const name = child.expression.expression.getText();

        if (!found.includes(name)) {
          found.push(name);
        }
      }

      ts.forEachChild(child, visit);
    };

    visit(node.body);
  }

  return found;
}

/**
 * The names a function body calls, one level deep.
 */
function calledNames(nodes) {
  const names = new Set();

  for (const node of nodes) {
    if (!node.body) {
      continue;
    }

    const visit = (child) => {
      if (ts.isCallExpression(child) && ts.isIdentifier(child.expression)) {
        names.add(child.expression.getText());
      }

      ts.forEachChild(child, visit);
    };

    visit(node.body);
  }

  return [...names];
}

function parameterFacts(nodes) {
  const declaration = nodes.find((node) => node.body) ?? nodes[0];

  const params = declaration.parameters ?? [];

  return params.map((param) => ({
    name: param.name.getText().replace(/^\.\.\./, ""),
    rest: Boolean(param.dotDotDotToken),
    type: param.type ? param.type.getText().replace(/\s+/g, " ") : "",
    optional: Boolean(param.questionToken) || Boolean(param.initializer),
    default: param.initializer ? param.initializer.getText().replace(/\s+/g, " ") : ""
  }));
}

function jsdocOf(node) {
  const blocks = node.jsDoc ?? [];

  if (blocks.length === 0) {
    return null;
  }

  const doc = blocks[blocks.length - 1];

  const result = {
    description: commentToText(doc.comment).trim(),
    params: {},
    returns: "",
    examples: [],
    see: [],
    since: "",
    deprecated: "",
    throws: rawThrows(doc)
  };

  for (const tag of doc.tags ?? []) {
    const name = tag.tagName.getText();

    const text = commentToText(tag.comment).trim().replace(/^-\s*/, "");

    switch (name) {
      case "param":
        result.params[tag.name?.getText() ?? ""] = text;

        break;
      case "returns":
      case "return":
        result.returns = text;

        break;
      case "example":
        result.examples.push(text);

        break;
      case "see":
        result.see.push(text);

        break;
      case "since":
        result.since = text;

        break;
      case "deprecated":
        result.deprecated = text;

        break;
      default:
        break;
    }
  }

  return result;
}

function signatureOf(nodes, source, kind) {
  if (kind !== "function") {
    return source.text
      .slice(nodes[0].getStart(source, false), nodes[0].getEnd())
      .split("\n")[0]
      .replace(/\s*\{$/, "")
      .replace(/^export\s+/, "")
      .trim();
  }

  return nodes
    .map((node) => {
      const start = node.getStart(source, false);

      const end = node.body ? node.body.getStart(source, false) : node.getEnd();

      return `${source.text
        .slice(start, end)
        .trim()
        .replace(/\s*\{$/, "")
        .replace(/^export\s+/, "")
        .replace(/\s+/g, " ")};`;
    })
    .join("\n");
}

function collectFacts() {
  const entries = [];

  for (const file of listFiles(SRC, (name) => name.endsWith(".ts") && name !== "index.ts").sort()) {
    const relPath = relative(SRC, file).split("\\").join("/");

    const source = ts.createSourceFile(
      file,
      readFileSync(file, "utf8"),
      ts.ScriptTarget.ESNext,
      true
    );

    const grouped = new Map();

    for (const statement of source.statements) {
      if (!isExported(statement)) {
        continue;
      }

      let name = null;

      let kind = null;

      if (ts.isFunctionDeclaration(statement) && statement.name) {
        name = statement.name.getText();
        kind = "function";
      } else if (ts.isClassDeclaration(statement) && statement.name) {
        name = statement.name.getText();
        kind = "class";
      } else if (ts.isInterfaceDeclaration(statement)) {
        name = statement.name.getText();
        kind = "interface";
      } else if (ts.isTypeAliasDeclaration(statement)) {
        name = statement.name.getText();
        kind = "type";
      } else if (ts.isEnumDeclaration(statement)) {
        name = statement.name.getText();
        kind = "enum";
      }

      if (!name) {
        continue;
      }

      if (!grouped.has(name)) {
        grouped.set(name, { kind, nodes: [] });
      }

      grouped.get(name).nodes.push(statement);
    }

    for (const [name, { kind, nodes }] of grouped) {
      const documented = nodes.filter((node) => (node.jsDoc ?? []).length > 0);

      const jsdoc = jsdocOf(documented[documented.length - 1] ?? nodes[nodes.length - 1]);

      if (!jsdoc || !jsdoc.description) {
        continue;
      }

      const declaration = nodes.find((node) => node.body) ?? nodes[0];

      entries.push({
        name,
        kind,
        module: moduleOf(relPath),
        relPath,
        referenceTopic: referenceTopicOf(relPath),
        signature: signatureOf(nodes, source, kind),
        params: kind === "function" ? parameterFacts(nodes) : [],
        returnType:
          kind === "function" && declaration.type
            ? declaration.type.getText().replace(/\s+/g, " ")
            : "",
        thrown: kind === "function" ? thrownClasses(nodes) : [],
        calls: kind === "function" ? calledNames(nodes) : [],
        jsdoc
      });
    }
  }

  return entries;
}

// --- rendering ------------------------------------------------------------

// JSDoc written for a file tree links with raw HTML: an external anchor to the
// Apps Script reference, or a relative one to a sibling source file. A topic is
// neither, so the anchor becomes a Markdown link — to the symbol's own page when
// the documentation has one, and to plain code when it does not.
function htmlAnchors(text, pages) {
  return text.replace(/<a\s+href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g, (_match, href, label) => {
    const name = label
      .replace(/<\/?code>/g, "")
      .replace(/\s+/g, " ")
      .trim();

    if (/^https?:/i.test(href)) {
      return `[\`${name}\`](${href})`;
    }

    return pages.has(name) ? `[\`${name}\`](${name}.md)` : `\`${name}\``;
  });
}

function resolveLinks(text, pages) {
  return htmlAnchors(text, pages).replace(/\{@link\s+([^}|\s]+)(\|[^}]*)?\}/g, (_match, target) => {
    const name = target.replace(/^.*[.#]/, "");

    return pages.has(name) ? `[\`${name}\`](${name}.md)` : `\`${name}\``;
  });
}

function firstSentence(text) {
  const clean = text.replace(/\s+/g, " ").trim();

  const match = clean.match(/^(.*?[.!?])(\s|$)/);

  return (match ? match[1] : clean).trim();
}

function escapeCell(text) {
  return text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

function renderPage(entry, language, content, sourceContent, pages, thrownBy) {
  const strings = language.strings;

  const jsdoc = entry.jsdoc;

  const translated = Boolean(content);

  const summary = content?.summary ?? firstSentence(jsdoc.description).replace(/`/g, "");

  const paragraphs =
    content?.description ??
    jsdoc.description
      .split(/\n\s*\n/)
      .map((p) => p.trim())
      .filter(Boolean);

  const lines = [];

  lines.push(`${MARKER} Source: src/${entry.relPath}. -->`);
  lines.push("");
  lines.push(`# ${entry.name}`);
  lines.push("");
  lines.push(`<link-summary>${summary.replace(/[<>]/g, "")}</link-summary>`);
  lines.push("");
  lines.push(
    `<web-summary>${entry.kind === "function" ? `${entry.name}()` : entry.name} — ${summary.replace(/[<>]/g, "")} apps-script-utils, ${language.name}.</web-summary>`
  );
  lines.push("");
  lines.push("<tldr>");
  lines.push(
    `<p>${strings.module}: <code>${entry.module}</code>${jsdoc.since ? ` · ${strings.since}: ${jsdoc.since}` : ""}${
      jsdoc.deprecated ? ` · <b>${strings.deprecated}</b>` : ""
    }</p>`
  );
  lines.push("</tldr>");
  lines.push("");

  if (!translated && language !== SOURCE_LANGUAGE) {
    lines.push(`> ${strings.englishNotice}`);
    lines.push("");
  }

  if (jsdoc.deprecated) {
    lines.push(
      `> **${strings.deprecated}.** ${resolveLinks(jsdoc.deprecated, pages).replace(/\n/g, " ")}`
    );
    lines.push("");
  }

  lines.push("```typescript");
  lines.push(entry.signature);
  lines.push("```");
  lines.push("");

  for (const paragraph of paragraphs) {
    lines.push(resolveLinks(paragraph, pages));
    lines.push("");
  }

  if (entry.params.length > 0) {
    lines.push(`## ${strings.parameters}`);
    lines.push("");
    lines.push(`| ${strings.parameter} | ${strings.type} | ${strings.description} |`);
    lines.push("| :--- | :--- | :--- |");

    for (const param of entry.params) {
      const described = content?.params?.[param.name] ?? jsdoc.params[param.name] ?? "";

      const flags = [];

      if (param.optional) {
        flags.push(`*(${strings.optional})*`);
      }

      if (param.default) {
        flags.push(`\`= ${param.default}\``);
      }

      lines.push(
        `| \`${param.rest ? "..." : ""}${param.name}\`${flags.length ? ` ${flags.join(" ")}` : ""} | ${
          param.type ? `\`${escapeCell(param.type)}\`` : "—"
        } | ${escapeCell(resolveLinks(described, pages)) || "—"} |`
      );
    }

    lines.push("");
  }

  const returns = content?.returns ?? jsdoc.returns;

  if (entry.returnType || returns) {
    const predicate = entry.returnType.match(/^(\w+) is (.+)$/);

    const shown = predicate ? "boolean" : entry.returnType;

    const described = returns ? resolveLinks(returns, pages).replace(/\s+/g, " ").trim() : "";

    lines.push(`## ${strings.returns}`);
    lines.push("");
    lines.push(shown ? `\`${shown}\`${described ? ` — ${described}` : ""}` : described);

    if (predicate) {
      lines.push("");
      lines.push(strings.narrows.replace("{name}", predicate[1]).replace("{type}", predicate[2]));
    }

    lines.push("");
  }

  const conditions = new Map();

  for (const raw of jsdoc.throws) {
    const { type, when } = throwsParts(raw);

    if (!type) {
      continue;
    }

    if (!conditions.has(type)) {
      conditions.set(type, []);
    }

    conditions.get(type).push(when.replace(/^If\s+/, ""));
  }

  for (const type of entry.thrown) {
    if (!conditions.has(type)) {
      conditions.set(type, [""]);
    }
  }

  if (content?.throws) {
    conditions.clear();

    for (const [type, when] of Object.entries(content.throws)) {
      // The prose names the exception; the code is what actually throws it.
      const reachable = new Set(entry.thrown);

      const pending = [...entry.calls];

      const visited = new Set();

      // A guard throws on behalf of whoever calls it, however many hops away.
      while (pending.length > 0) {
        const called = pending.pop();

        if (visited.has(called)) {
          continue;
        }

        visited.add(called);

        for (const indirect of thrownBy.get(called)?.thrown ?? []) {
          reachable.add(indirect);
        }

        pending.push(...(thrownBy.get(called)?.calls ?? []));
      }

      if (reachable.size > 0 && !reachable.has(type) && !BUILT_IN_ERRORS.has(type)) {
        console.warn(
          `  ${entry.name}: prose says it throws ${type}; reachable from the code: ${[...reachable].join(", ")}`
        );
      }

      conditions.set(type, Array.isArray(when) ? when : [when]);
    }
  }

  if (conditions.size > 0) {
    lines.push(`## ${strings.throws}`);
    lines.push("");
    lines.push(`| ${strings.exception} | ${strings.condition} |`);
    lines.push("| :--- | :--- |");

    for (const [type, whens] of conditions) {
      for (const when of whens) {
        lines.push(`| \`${escapeCell(type)}\` | ${escapeCell(resolveLinks(when, pages)) || "—"} |`);
      }
    }

    lines.push("");
  }

  // Prose written by hand is Markdown; a JSDoc `@example` is bare code.
  const authoredExamples = sourceContent?.examples;

  const fallbackExamples = authoredExamples ?? jsdoc.examples.map((body) => ({ title: "", body }));

  const examples = (content?.examples ?? fallbackExamples).map((example, position) => ({
    title: example.title ?? "",
    body: example.body ?? fallbackExamples[position]?.body ?? "",
    markdown: Boolean(content?.examples ? content.examples : authoredExamples)
  }));

  if (examples.length > 0) {
    lines.push(`## ${strings.examples}`);
    lines.push("");

    for (const example of examples) {
      const body = (example.body ?? "").trim();

      if (example.title) {
        lines.push(`### ${example.title}`);
        lines.push("");
      }

      if (example.markdown) {
        lines.push(body);
        lines.push("");

        continue;
      }

      if (!body.includes("```")) {
        lines.push(["```javascript", body, "```"].join("\n"));
        lines.push("");

        continue;
      }

      const fenceAt = body.indexOf("```");

      const caption = body
        .slice(0, fenceAt)
        .trim()
        .replace(/^\((.*)\)$/s, "$1");

      if (caption && !example.title) {
        lines.push(`_${caption.replace(/\s+/g, " ")}_`);
        lines.push("");
      }

      lines.push(body.slice(fenceAt).trim());
      lines.push("");
    }
  }

  const seen = new Set();

  const related = [];

  for (const raw of content?.seeAlso ?? jsdoc.see) {
    const target =
      typeof raw === "string"
        ? ((raw.match(/\{@link\s+([^}|\s]+)/) ?? [])[1] ?? raw.trim())
        : raw.name;

    const short = String(target).replace(/^.*[.#]/, "");

    if (!pages.has(short) || short === entry.name || seen.has(short)) {
      continue;
    }

    seen.add(short);

    const note = typeof raw === "object" && raw.note ? ` — ${raw.note}` : "";

    related.push(`- [\`${short}\`](${short}.md)${note}`);
  }

  // A `@see` that points outside the documentation — Google's reference, most of
  // the time — is not a topic, so the filter above drops it. It survives here as
  // the link it is, minus the one that points back at this very page.
  for (const raw of jsdoc.see) {
    if (typeof raw !== "string") {
      continue;
    }

    const link = htmlAnchors(raw, pages).match(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/);

    if (!link) {
      continue;
    }

    const [, label, url] = link;

    if (url.toLowerCase().endsWith(`/${entry.name.toLowerCase()}.html`) || seen.has(url)) {
      continue;
    }

    seen.add(url);

    related.push(`- [${label}](${url})`);
  }

  lines.push(`## ${strings.seeAlso}`);
  lines.push("");

  if (related.length > 0) {
    lines.push(...related);
  }

  lines.push(`- [](${entry.referenceTopic})`);
  lines.push("");
  lines.push(`## ${strings.source}`);
  lines.push("");
  lines.push(`[\`src/${entry.relPath}\`](${REPO}/src/${entry.relPath})`);
  lines.push("");

  return lines.join("\n");
}

/**
 * Rebuilds the tables of a reference topic in another language.
 *
 * The rows come from the English topic — which functions are listed, in what
 * order, with what return type — and each description is replaced by the
 * summary written for that language. A translated reference topic therefore
 * carries only its own prose and a `<!-- table -->` line where each table goes.
 */
/**
 * Translates a table's column heading.
 */
function label(heading, strings) {
  const map = {
    "Function": strings.tableFunction,
    "Return type": strings.tableReturns,
    "Brief description": strings.tableDescription,
    "Description": strings.tableDescriptionShort,
    "Exception": strings.tableException,
    "Abstract": strings.tableAbstract,
    "Interface": strings.tableInterface
  };

  return map[heading] ?? heading;
}

function localiseTables(english, translated, language, summaries) {
  const tables = [];

  let current = null;

  for (const line of english.split("\n")) {
    const isRow = line.startsWith("|");

    if (isRow && current === null) {
      current = [];
      tables.push(current);
    } else if (!isRow) {
      current = null;
    }

    if (isRow) {
      current.push(line);
    }
  }

  const strings = language.strings;

  const rendered = tables.map((rows) =>
    rows
      .map((row, index) => {
        const cells = row.split("|").slice(1, -1);

        if (index === 0) {
          return `| ${cells.map((cell) => label(cell.trim(), strings)).join(" | ")} |`;
        }

        if (index === 1) {
          return `|${cells.map(() => " :--- ").join("|")}|`;
        }

        if (cells.length < 2) {
          return row;
        }

        const name = (cells[0].match(/\[`(\w+)`\]/) ?? [])[1];

        const summary = name ? summaries.get(name) : null;

        if (!summary) {
          return `|${cells.join("|")}|`;
        }

        const localised = cells.slice();

        localised[localised.length - 1] = ` ${summary.replace(/\|/g, "\\|")} `;

        return `|${localised.join("|")}|`;
      })
      .join("\n")
  );

  let position = 0;

  return translated.replace(/<!--\s*table\s*\d*\s*-->/g, () => rendered[position++] ?? "");
}

// --- the language projects -------------------------------------------------

function localiseTree(tree, language) {
  let out = tree;

  out = out.replace(/name="[^"]*"/, `name="${language.instanceName}"`);
  out = out.replace(/toc-title="Guides"/g, `toc-title="${language.strings.tocGuides}"`);
  out = out.replace(/toc-title="Modules"/g, `toc-title="${language.strings.tocModules}"`);
  out = out.replace(
    /toc-title="Function reference"/g,
    `toc-title="${language.strings.tocReference}"`
  );

  return out;
}

function copyInto(fromDir, toDir, filter = () => true) {
  const files = listFiles(fromDir, filter);

  for (const file of files) {
    const target = join(toDir, relative(fromDir, file));

    mkdirSync(dirname(target), { recursive: true });

    const source = readFileSync(file);

    const existing = (() => {
      try {
        return readFileSync(target);
      } catch {
        return null;
      }
    })();

    if (existing && existing.equals(source)) {
      continue;
    }

    if (CHECK) {
      stale.push(relative(ROOT, target));

      continue;
    }

    copyFileSync(file, target);
    written += 1;
  }
}

const VERSION = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;

// --- run ------------------------------------------------------------------

const entries = collectFacts();

// The summaries feed the reference tables of the translated projects.
const summaries = new Map(LANGUAGES.map((language) => [language.code, new Map()]));

for (const language of LANGUAGES) {
  for (const entry of entries) {
    const authored = readIfExists(join(CONTENT, language.code, "functions", `${entry.name}.json`));

    if (authored) {
      summaries.get(language.code).set(entry.name, JSON.parse(authored).summary);
    }
  }
}

const pages = new Set(entries.map((entry) => entry.name));

// What each function throws, so a caller's page can name its guard's exception.
const thrownBy = new Map(
  entries.map((entry) => [entry.name, { thrown: entry.thrown, calls: entry.calls }])
);

const sourceRoot = join(ROOT, SOURCE_LANGUAGE.root);

const missing = new Map();

for (const language of LANGUAGES) {
  const root = join(ROOT, language.root);

  const topics = join(root, "topics");

  const untranslated = [];

  // 1. Project configuration, the search widget and the structured head.
  emit(join(root, "buildprofiles.xml"), buildProfiles(language));
  emit(join(root, "head.html"), await pretty(headHtml(language), join(root, "head.html")));
  emit(join(root, "search.html"), await pretty(searchHtml(language), join(root, "search.html")));

  // The configuration is the same everywhere but for the version, which comes
  // from the package, so even the English project is written rather than kept.
  emit(join(root, "writerside.cfg"), writersideCfg(VERSION));

  if (language !== SOURCE_LANGUAGE) {
    emit(
      join(root, "asu.tree"),
      localiseTree(readFileSync(join(sourceRoot, "asu.tree"), "utf8"), language)
    );
    copyInto(join(sourceRoot, "images"), join(root, "images"), () => true);
    copyInto(join(sourceRoot, "snippets"), join(root, "snippets"), (name) => name.endsWith(".ts"));
  }

  // 2. The narrative topics: translated where a translation exists, English otherwise.
  if (language !== SOURCE_LANGUAGE) {
    for (const file of listFiles(join(sourceRoot, "topics"), (name) => name.endsWith(".md"))) {
      const name = relative(join(sourceRoot, "topics"), file);

      if (pages.has(name.replace(/\.md$/, ""))) {
        continue;
      }

      const translation = readIfExists(join(CONTENT, language.code, "topics", name));

      if (translation) {
        const body = translation.includes("<!-- table")
          ? localiseTables(
              readFileSync(file, "utf8"),
              translation,
              language,
              summaries.get(language.code)
            )
          : translation;

        emit(
          join(topics, name),
          await pretty(`${MARKER} Translated topic. -->\n\n${body.trim()}\n`, join(topics, name))
        );

        continue;
      }

      const english = readFileSync(file, "utf8");

      const withNotice = english.replace(/^(# .*\n)/, `$1\n> ${language.strings.englishNotice}\n`);

      untranslated.push(name);
      emit(
        join(topics, name),
        await pretty(
          `${MARKER} Untranslated topic, shown in English. -->\n\n${withNotice.trim()}\n`,
          join(topics, name)
        )
      );
    }
  }

  // 3. A page per exported symbol.
  for (const entry of entries) {
    const target = join(topics, `${entry.name}.md`);

    const existing = readIfExists(target);

    if (existing !== null && !existing.startsWith(MARKER)) {
      kept += 1;

      continue;
    }

    const authored = readIfExists(join(CONTENT, language.code, "functions", `${entry.name}.json`));

    const content = authored ? JSON.parse(authored) : null;

    const englishFile = readIfExists(
      join(CONTENT, SOURCE_LANGUAGE.code, "functions", `${entry.name}.json`)
    );

    const english = englishFile ? JSON.parse(englishFile) : null;

    if (!content) {
      untranslated.push(`${entry.name}.md`);
    }

    emit(
      target,
      await pretty(renderPage(entry, language, content, english, pages, thrownBy), target)
    );
  }

  missing.set(language.code, untranslated);
}

// 4. The reference tables of the source project point at the pages.
const tableLink = new RegExp(
  `\\[\`(\\w+)\`\\]\\(${REPO.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}/src/[^)]+\\)`,
  "g"
);

for (const topic of new Set(entries.map((entry) => entry.referenceTopic))) {
  const path = join(sourceRoot, "topics", topic);

  const before = readFileSync(path, "utf8");

  emit(
    path,
    await pretty(
      before.replace(tableLink, (match, name) =>
        pages.has(name) ? `[\`${name}\`](${name}.md)` : match
      ),
      path
    )
  );
}

// 5. Every page has to be reachable: the Writerside build refuses to link to a
// topic the navigation does not list, and the tree is written by hand.
const listed = new Set(
  [...readFileSync(join(sourceRoot, "asu.tree"), "utf8").matchAll(/topic="([^"]+)"/g)].map(
    (match) => match[1]
  )
);

const unlisted = entries.map((entry) => `${entry.name}.md`).filter((name) => !listed.has(name));

if (unlisted.length > 0) {
  console.error(`Not listed in ${SOURCE_LANGUAGE.root}/asu.tree, so nothing can link to them:`);

  for (const name of unlisted.sort()) {
    console.error(`  ${name}`);
  }

  process.exit(1);
}

// 6. What still needs prose, per language.
const coverage = [
  "# Documentation coverage",
  "",
  "Generated by `scripts/docs/generate-topics.mjs`. A page counts as covered when",
  "prose for it exists in `docs/content/<language>/` — a JSON file per function, a",
  "Markdown file per narrative topic — or when it was written by hand in the",
  "language project itself.",
  "",
  "| Language | Pages | Written | Awaiting prose |",
  "| :------- | ----: | ------: | -------------: |"
];

for (const language of LANGUAGES) {
  const gaps = missing.get(language.code) ?? [];

  const total = entries.length + (language === SOURCE_LANGUAGE ? 0 : 15);

  coverage.push(`| ${language.name} | ${total} | ${total - gaps.length} | ${gaps.length} |`);
}

coverage.push("");

for (const language of LANGUAGES) {
  const gaps = missing.get(language.code) ?? [];

  if (gaps.length === 0) {
    continue;
  }

  coverage.push(`## ${language.name}`, "", `${gaps.length} pages awaiting prose:`, "", "```text");
  coverage.push(...gaps.sort());
  coverage.push("```", "");
}

emit(join(CONTENT, "COVERAGE.md"), await pretty(coverage.join("\n"), join(CONTENT, "COVERAGE.md")));

if (CHECK && stale.length > 0) {
  console.error("Documentation is out of date. Run: npm run docs:generate");

  for (const path of stale.slice(0, 20)) {
    console.error(`  ${path}`);
  }

  if (stale.length > 20) {
    console.error(`  … and ${stale.length - 20} more`);
  }

  process.exit(1);
}

console.log(
  `${entries.length} symbols · ${LANGUAGES.length} languages · ${written} files written · ${kept} hand-written pages kept`
);
