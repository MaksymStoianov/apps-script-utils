/**
 * Builds the reference pages of every language site.
 *
 * What a page says comes from two places, and neither of them is a guess:
 *
 * - the **code**, read with the TypeScript compiler: the signature, the
 *   parameters and their types, the return type, the exceptions the body
 *   actually throws, the release a symbol appeared in;
 * - the **prose**, written by hand in `docs/content/<language>/functions/`,
 *   one small JSON file per function per language.
 *
 * The JSDoc is a fallback, used only where prose has not been written yet, and
 * every such page is listed in `docs/content/COVERAGE.md`. A page that exists in
 * a language project without this file's marker comment was written by hand and
 * is left alone.
 *
 * The English project, `docs/writerside/`, is the source project; the other
 * four are generated whole — configuration, search widget, images and snippets
 * included — so the sites cannot drift apart.
 *
 * Usage: `node scripts/docs/generate-topics.mjs [--check]`
 */

