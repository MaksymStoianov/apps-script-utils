/**
 * Checks the documented examples against the code they document.
 *
 * Every line of an English example that states its own result — `expr; // => 42`
 * or `expr; // throws SomeException` — becomes an assertion in a generated test
 * file, which is then run with Vitest. A sample that stops being true fails the
 * suite instead of misleading a reader.
 *
 * Lines that are not self-contained (a sheet, a variable defined elsewhere) are
 * skipped and counted.
 *
 * Usage: `node scripts/docs/verify-examples.mjs`
 */

import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

const CONTENT = join(ROOT, "docs/content/en/functions");

const OUT = join(ROOT, "test/docs");

/**
 * Names an example may use that come from the runtime, not from the package.
 */
const GLOBALS = new Set([
  "it",
  "expect",
  "describe",
  "Function",
  "Symbol",
  "Number",
  "RegExp",
  "Error",
  "Math",
  "Logger",
  "String",
  "Boolean",
  "Object",
  "Array",
  "Set",
  "Map",
  "Date",
  "JSON",
  "SpreadsheetApp"
]);

const RESULT = /^([A-Za-z_$][\w$]*\(.*\));\s*\/\/\s*=>\s*(.+?)\s*$/;

const THROWS = /^([A-Za-z_$][\w$]*\(.*\));\s*\/\/\s*throws\s+([A-Za-z_$][\w$]*)/;

/**
 * `[[1], [2]] (size defaults to 1)` — keep the value, drop the aside.
 */
function parseExpected(text) {
  const candidates = [text, text.replace(/\s*\(.*\)\s*$/, "")];

  for (const candidate of candidates) {
    try {
      new Function(`return (${candidate});`)();

      return candidate;
    } catch {
      continue;
    }
  }

  return null;
}

/**
 * Names the package exports, so an example may use one without being skipped.
 */
const KNOWN = new Set(
  readdirSync(CONTENT)
    .map((file) => file.replace(/\.json$/, ""))
    .concat(
      readdirSync(join(ROOT, "src/exception"))
        .filter((file) => /^[A-Z]/.test(file))
        .map((file) => file.replace(/\.ts$/, ""))
    )
);

/**
 * Whether the arguments of a call can be evaluated here. An example that needs
 * a spreadsheet, a slide or any other live Apps Script object cannot be, and is
 * counted as skipped rather than reported as a failure.
 */
function evaluable(args) {
  try {
    new Function(`return [${args}];`)();

    return true;
  } catch (error) {
    const missing = /(\w+) is not defined/.exec(String(error));

    return Boolean(missing && KNOWN.has(missing[1]));
  }
}

const assertions = [];

const used = new Set();

let skipped = 0;

for (const file of readdirSync(CONTENT).sort()) {
  const content = JSON.parse(readFileSync(join(CONTENT, file), "utf8"));

  const name = file.replace(/\.json$/, "");

  for (const example of content.examples ?? []) {
    const body = example.body ?? "";

    for (const block of body.matchAll(/```javascript\n([\s\S]*?)```/g)) {
      for (const raw of block[1].split("\n")) {
        const line = raw.trim();

        if (!line || line.startsWith("//")) {
          continue;
        }

        const thrown = line.match(THROWS);

        if (thrown && !evaluable(thrown[1].replace(/^[A-Za-z_$][\w$]*\(/, "").replace(/\)$/, ""))) {
          skipped += 1;

          continue;
        }

        if (thrown) {
          assertions.push(
            `  it(${JSON.stringify(`${name}: ${line}`)}, () => {\n` +
              `    expect(() => ${thrown[1]}).toThrow(${thrown[2]});\n  });`
          );
          used.add(thrown[2]);

          continue;
        }

        const result = line.match(RESULT);

        if (!result) {
          skipped += 1;

          continue;
        }

        const expected = parseExpected(result[2]);

        const args = result[1].replace(/^[A-Za-z_$][\w$]*\(/, "").replace(/\)$/, "");

        if (expected === null || !evaluable(args)) {
          skipped += 1;

          continue;
        }

        // `requireX(value) // => value` documents identity, not a deep copy.
        const call = result[1].match(/^([A-Za-z_$][\w$]*)\((.*)\)$/);

        const identity = call && call[2].trim() === expected.trim();

        assertions.push(
          identity
            ? `  it(${JSON.stringify(`${name}: ${line}`)}, () => {\n` +
                `    const value = ${expected};\n` +
                `    expect(${call[1]}(value)).toBe(value);\n  });`
            : `  it(${JSON.stringify(`${name}: ${line}`)}, () => {\n` +
                `    expect(${result[1]}).toStrictEqual(${expected});\n  });`
        );
      }
    }
  }
}

mkdirSync(OUT, { recursive: true });

const file = join(OUT, "examples.test.ts");

writeFileSync(
  file,
  [
    "// Generated by scripts/docs/verify-examples.mjs. Do not edit, do not commit.",
    'import { describe, expect, it } from "vitest";',
    'import * as asu from "@/index";',
    "",
    "const {",
    ...[
      ...new Set([
        ...[...assertions.join("\n").matchAll(/\b([A-Za-z_$][\w$]*)\(/g)].map((match) => match[1]),
        ...used
      ])
    ]
      .filter((symbol) => !GLOBALS.has(symbol))
      .sort()
      .map((symbol) => `  ${symbol},`),
    "} = asu as never;",
    "",
    'describe("documented examples", () => {',
    ...assertions,
    "});",
    ""
  ].join("\n")
);

const run = spawnSync("npx", ["vitest", "run", "test/docs/examples.test.ts"], {
  cwd: ROOT,
  encoding: "utf8"
});

process.stdout.write(run.stdout ?? "");
process.stderr.write(run.stderr ?? "");

rmSync(OUT, { recursive: true, force: true });

console.log(
  `${assertions.length} documented results checked, ${skipped} lines skipped as not self-contained`
);

process.exit(run.status ?? 1);
